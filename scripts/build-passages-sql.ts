/**
 * Builds supabase/maintenance/knowledge-2026-11/04_verified_passages.sql from
 * the REAL embeddings in .kb-preflight/embeddings.json (npm run kb:preflight).
 * The SQL inserts exactly the rows scripts/ingest-knowledge.ts would insert —
 * same columns, metadata, content_hash, embedding model — but with the
 * vectors that were tested, so production gets the reviewed artifact and
 * needs no service-role key. Refuses stale or malformed embeddings.
 *
 *   npx tsx scripts/build-passages-sql.ts
 *
 * The output is git-ignored (≈0.5 MB of vectors); its SHA-256 is printed for
 * the preflight report and checked again before applying.
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIR = join(process.cwd(), 'data', 'knowledge', 'verified-2026-11')
const OUT = join(
  process.cwd(),
  'supabase',
  'maintenance',
  'knowledge-2026-11',
  '04_verified_passages.sql',
)
const MODEL = '@cf/google/embeddinggemma-300m'
const ENTITY_CODE: Record<string, string> = {
  commerce: 'mc',
  telecom: 'cst',
  municipality: 'balady',
  water: 'nwc',
  electricity: 'sec',
}

type Entry = {
  title: string
  content: string
  entity: string
  sector: string
  documentType: string
  sourceUrl: string
  sourceLabel: string
  reviewedAt: string
  sourceId?: string
  quote?: string
  kbVersion?: string
}
const emb = JSON.parse(
  readFileSync(join(process.cwd(), '.kb-preflight', 'embeddings.json'), 'utf8'),
) as {
  model: string
  dimension: number
  passages: { file: string; title: string; contentHash: string; embedding: number[] }[]
}
if (emb.model !== MODEL || emb.dimension !== 768)
  throw new Error('Embeddings are not embeddinggemma-300m / 768.')
const byHash = new Map(emb.passages.map((p) => [p.contentHash, p]))

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const rows: string[] = []
let n = 0
for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith('.json'))
  .sort()) {
  for (const e of JSON.parse(readFileSync(join(DIR, file), 'utf8')) as Entry[]) {
    const hash = createHash('sha256').update(e.content).digest('hex')
    const p = byHash.get(hash)
    if (!p)
      throw new Error(
        `No embedding for "${e.title}" — passages changed; rerun npm run kb:preflight.`,
      )
    if (p.embedding.length !== 768 || p.embedding.some((x) => !Number.isFinite(x)))
      throw new Error(`Malformed embedding for "${e.title}".`)
    if (p.embedding.every((x) => x === p.embedding[0]))
      throw new Error(`Constant (placeholder-like) vector for "${e.title}".`)
    const metadata = {
      source_url: e.sourceUrl,
      source_label: e.sourceLabel,
      reviewed_at: e.reviewedAt,
      ...(e.sourceId ? { source_id: e.sourceId } : {}),
      ...(e.quote ? { source_quote: e.quote } : {}),
      ...(e.kbVersion ? { kb_version: e.kbVersion } : {}),
    }
    const code = ENTITY_CODE[e.sector]
    if (!code) throw new Error(`Unknown sector ${e.sector}`)
    n++
    rows.push(`  if not exists (select 1 from public.knowledge_documents where content_hash = ${q(hash)}) then
    select gs.id into v_service from public.government_services gs join public.government_entities ge on ge.id = gs.entity_id where ge.code = ${q(code)};
    select id into v_type from public.complaint_types where code = ${q(`${e.sector}_general`)};
    if v_service is null or v_type is null then raise exception 'Unresolved service/complaint type for ${e.sector}. Nothing changed.'; end if;
    insert into public.knowledge_documents (title, content, entity, sector, document_type, service_id, complaint_type_id, source_file, metadata, embedding, embedding_model, content_hash, is_active)
    values (${q(e.title)}, ${q(e.content)}, ${q(e.entity)}, ${q(e.sector)}, ${q(e.documentType)}, v_service, v_type, ${q(file)}, ${q(JSON.stringify(metadata))}::jsonb,
      '[${p.embedding.join(',')}]', ${q(MODEL)}, ${q(hash)}, true);
    v_inserted := v_inserted + 1;
  end if;`)
  }
}
const sql = `-- GENERATED by scripts/build-passages-sql.ts from .kb-preflight/embeddings.json — do not edit.
-- Inserts the ${n} verified passages with their REAL embeddings (${MODEL}, 768 dims),
-- exactly as scripts/ingest-knowledge.ts would (idempotent by content_hash). One atomic block.
do $kb04$
declare
  v_service uuid;
  v_type uuid;
  v_inserted integer := 0;
begin
${rows.join('\n')}
  raise notice 'verified passages inserted: % (of ${n})', v_inserted;
end
$kb04$;
`
writeFileSync(OUT, sql)
console.log(
  `04_verified_passages.sql: ${n} passages, sha256 ${createHash('sha256').update(sql).digest('hex')}`,
)
